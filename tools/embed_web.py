# PlatformIO pre-build script: gzip web/*.html into include/web_assets.h.
import gzip, os
try:
    Import("env")  # noqa: F821
    root = env["PROJECT_DIR"]  # noqa: F821
except NameError:
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

src = os.path.join(root, "web")
out = os.path.join(root, "include", "web_assets.h")
parts = ["// Generated by tools/embed_web.py from web/ - do not edit.\n#pragma once\n#include <stdint.h>\n#include <stddef.h>\n"]
for name in sorted(os.listdir(src)):
    if not name.endswith((".html", ".js", ".css")):
        continue
    data = gzip.compress(open(os.path.join(src, name), "rb").read(), 9, mtime=0)
    sym = "WEB_" + name.upper().replace(".", "_").replace("-", "_")
    body = ",".join("0x%02x" % b for b in data)
    parts.append("static const uint8_t %s[] = {%s};\nstatic const size_t %s_LEN = %d;\n" % (sym, body, sym, len(data)))
text = "\n".join(parts)
if not os.path.exists(out) or open(out).read() != text:
    open(out, "w").write(text)
    print("embed_web: wrote", out)
